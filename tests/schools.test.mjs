import { PGlite } from '@electric-sql/pglite';
import { pg_trgm } from '@electric-sql/pglite/contrib/pg_trgm';
import { beforeAll,afterAll,it,expect } from 'vitest';
import { readFileSync,readdirSync } from 'node:fs';
import { storageSchema } from './helpers/storage-schema.mjs';
let db;
const a='11111111-1111-4111-8111-111111111111',b='22222222-2222-4222-8222-222222222222';
beforeAll(async()=>{
 db=new PGlite({extensions:{pg_trgm}});await db.exec(`create role anon;create role authenticated;create schema auth;create table auth.users(id uuid primary key);create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;grant usage on schema public,auth to anon,authenticated;grant execute on function auth.uid() to anon,authenticated;insert into auth.users values('${a}'),('${b}');`);
 await db.exec(storageSchema);
 for(const f of readdirSync('supabase/migrations').filter(f=>f.endsWith('.sql')).sort())await db.exec(readFileSync('supabase/migrations/'+f,'utf8'));
});
afterAll(async()=>db?.close());
it('isola escolas, currículos e mídias entre dois responsáveis e anônimo',async()=>{
 await db.exec(`set role authenticated;select set_config('request.jwt.claim.sub','${a}',false);`);
 const school=(await db.query("insert into schools(name,slug) values('Escola A','escola-a') returning id")).rows[0];
 const curriculum=(await db.query("insert into school_curricula(school_id,title,content) values($1,'Branca',$2) returning id",[school.id,{title:'Branca',description:'Demonstração',grades:[]}])).rows[0];
 await db.query("insert into school_media(school_id,title,media_kind,media_url,creator,permission_note,consent_confirmed,rights_confirmed) values($1,'Vídeo privado','video','https://example.org/private.mp4','Professor','Autorização registrada',true,true)",[school.id]);
 await db.exec(`select set_config('request.jwt.claim.sub','${b}',false);`);
 expect((await db.query('select * from school_curricula')).rows).toEqual([]);
 expect((await db.query('select title from school_media')).rows).toEqual([]);
 expect((await db.query("update schools set name='Invadida' where id=$1 returning id",[school.id])).rows).toEqual([]);
 await expect(db.query("insert into school_curricula(school_id,title,content) values($1,'Ataque','{}')",[school.id])).rejects.toThrow(/foreign key/);
 await expect(db.query("insert into school_curricula(school_id,owner_user_id,title,content) values($1,$2,'Ataque','{}')",[school.id,a])).rejects.toThrow(/row-level security/);
 await db.exec(`select set_config('request.jwt.claim.sub','${a}',false);`);
 await db.query("update school_curricula set visibility='public' where id=$1",[curriculum.id]);
 await db.exec("reset role;set role anon;select set_config('request.jwt.claim.sub','',false);");
 expect((await db.query('select title from school_curricula')).rows).toEqual([{title:'Branca'}]);
 expect((await db.query('select id,name,slug from schools')).rows).toHaveLength(1);
 await expect(db.query('select owner_user_id from schools')).rejects.toThrow(/permission denied/);
 expect((await db.query('select title from school_media')).rows).toEqual([]);
 await db.exec(`reset role;set role authenticated;select set_config('request.jwt.claim.sub','${a}',false);`);
 await expect(db.query("insert into school_media(school_id,title,media_kind,media_url,visibility,creator,permission_note) values($1,'Sem consentimento','video','https://example.org/x','public','Autor','Direitos')",[school.id])).rejects.toThrow();
 await db.query("update school_curricula set visibility='private' where id=$1",[curriculum.id]);
 await db.query("update school_media set visibility='public' where school_id=$1",[school.id]);
 await db.exec(`select set_config('request.jwt.claim.sub','${b}',false);`);
 expect((await db.query('select permission_note from school_media')).rows).toEqual([]);
 await db.exec("reset role;set role anon;select set_config('request.jwt.claim.sub','',false);");
 expect((await db.query('select title from school_media')).rows).toHaveLength(1);
 expect((await db.query('select title from school_curricula')).rows).toEqual([]);
});
