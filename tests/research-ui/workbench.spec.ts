import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

const audited = resolve('content/research/gemini-2026-11-06/audit.json');
const raw = JSON.parse(readFileSync('content/research/gemini-2026-11-06/original/tecnicas_rascunho.json', 'utf8'));
test('abre115 candidatos, compara108 e filtra nomes/estado/lote sem backend', async ({ page }) => {
  const backend: string[] = [];
  page.on('request', request => { if (request.url().includes('.supabase.co')) backend.push(request.url()); });
  await page.goto('/pesquisa-local');
  await expect(page.getByLabel('Arquivo JSON de pesquisa')).toBeEnabled();
  await page.getByLabel('Arquivo JSON de pesquisa').setInputFiles(audited);
  await expect(page.getByRole('status')).toContainText('115 candidatos em pesquisa. Nenhum aprovado.');
  await expect(page.getByRole('status')).toContainText('108 registros existentes');
  await expect(page.getByRole('region', { name: 'Comparação ap-chagi', exact: true })).toContainText('Chute frontal');
  await page.getByLabel('Buscar português, Hangul, romanização ou ID').fill('앞차기'.normalize('NFD'));
  await expect(page.getByRole('navigation', { name: 'Candidatos de pesquisa' }).getByRole('button')).toHaveCount(2);
  await expect(page.getByRole('navigation', { name: 'Candidatos de pesquisa' })).toContainText('TC-CHA-015');
  await page.getByLabel('Buscar português, Hangul, romanização ou ID').fill('chute frontal');
  await expect(page.getByRole('navigation', { name: 'Candidatos de pesquisa' }).getByRole('button')).toHaveCount(3);
  await page.keyboard.press('Tab'); await expect(page.getByRole('combobox', { name: 'Categoria', exact: true })).toBeFocused();
  await page.getByLabel('Buscar português, Hangul, romanização ou ID').clear();
  await page.getByRole('combobox', { name: 'Lote de trabalho', exact: true }).selectOption('6');
  await expect(page.getByRole('navigation', { name: 'Candidatos de pesquisa' }).getByRole('button')).toHaveCount(15);
  await page.getByRole('combobox', { name: 'Lote de trabalho', exact: true }).selectOption('');
  await page.getByRole('combobox', { name: 'Estado documental', exact: true }).selectOption('conflicting');
  await expect(page.getByRole('navigation', { name: 'Candidatos de pesquisa' }).getByRole('button')).toHaveCount(11);
  const csvPromise = page.waitForEvent('download'); await page.getByRole('button', { name: 'Exportar resultados CSV' }).click();
  expect((await csvPromise).suggestedFilename()).toBe('candidatos-filtrados.csv');
  expect(backend).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
});
test('registra checklist/proposta, exporta e reabre histórico sem homologação', async ({ page }) => {
  await page.goto('/pesquisa-local'); await expect(page.getByLabel('Arquivo JSON de pesquisa')).toBeEnabled(); await page.getByLabel('Arquivo JSON de pesquisa').setInputFiles(audited);
  await page.getByLabel('Nome e vínculo do responsável').fill('Fixture isolada de navegador');
  await page.getByRole('button', { name: 'Iniciar sessão de observações' }).click();
  await page.getByLabel('Fonte e página conferidas', { exact: true }).check();
  await page.getByLabel('Observação para revisão').fill('Verificar tradução com professor e especialista em coreano.');
  await page.getByRole('button', { name: 'Registrar observação', exact: true }).click();
  await page.getByText('Propor correção com justificativa e evidência', { exact: true }).click();
  await page.getByLabel('Campo da proposta').selectOption('name_pt_raw');
  await page.getByLabel('Valor proposto').fill('Fixture sintética — somente teste');
  await page.getByLabel('Justificativa').fill('Esta proposta sintética verifica a preservação do original.');
  await page.getByLabel('URL HTTPS da evidência').fill('https://example.org/test-fixture');
  await page.getByLabel('Página ou seção da evidência').fill('§1 > Fixture isolada');
  await page.getByRole('button', { name: 'Registrar proposta de correção' }).click();
  await expect(page.locator('.research-history li')).toHaveCount(3);
  await page.locator('.research-session summary').click();
  const promise = page.waitForEvent('download'); await page.getByRole('button', { name: 'Exportar sessão e histórico' }).click();
  const file = await (await promise).path(); expect(file).not.toBeNull();
  const session = JSON.parse(readFileSync(file!, 'utf8'));
  expect(session.identity_assurance).toBe('self_declared_local'); expect(session.events).toHaveLength(3);
  expect(session.events[2].data.original).toBe(raw.records[0].name_pt_raw);
  await page.reload(); await expect(page.getByLabel('Arquivo JSON de pesquisa')).toBeEnabled(); await page.getByLabel('Arquivo JSON de pesquisa').setInputFiles(audited);
  await page.getByLabel('Reabrir sessão JSON').setInputFiles(file!);
  await expect(page.locator('.research-history li')).toHaveCount(3);
  await expect(page.getByRole('status')).toContainText('Nenhum aprovado');
  await expect(page.getByRole('button', { name: /^Aprovar|^Publicar/ })).toHaveCount(0);
});
test('rejeita falha parcial e renderiza texto externo sem executar HTML', async ({ page }) => {
  await page.goto('/pesquisa-local');
  await expect(page.getByLabel('Arquivo JSON de pesquisa')).toBeEnabled();
  const invalid = structuredClone(raw); invalid.records.at(-1).publication_status = 'published';
  await page.getByLabel('Arquivo JSON de pesquisa').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(invalid)) });
  await expect(page.getByRole('alert')).toBeVisible();
  await expect(page.getByRole('status')).toHaveCount(0);
  const xss = structuredClone(raw); xss.records[0].name_pt_raw = '<img src=x onerror="window.__researchXss=1">';
  await page.getByLabel('Arquivo JSON de pesquisa').setInputFiles({ name: 'isolated-fixture.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(xss)) });
  await expect(page.getByText('<img src=x onerror="window.__researchXss=1">', { exact: true }).first()).toBeVisible();
  expect(await page.evaluate(() => (window as any).__researchXss)).toBeUndefined();
  await expect(page.locator('.research-lab img')).toHaveCount(0);
});
